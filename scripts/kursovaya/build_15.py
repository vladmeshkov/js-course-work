DEFAULT_ORDER = ['uc', 'seq', 'act', 'st', 'comp', 'dep']
CLOSING = 'Построенные модели описывают программное средство с функциональной, динамической и физической точек зрения и согласованы между собой и с информационной моделью из подраздела 1.4: актёры и варианты использования соответствуют ролям и правам доступа, последовательность и состояния – статусам заявок в базе данных, компоненты – слоям программы.'


def layout():
    path = os.path.join(KURS, 'src', 'layout-1.5.json')
    if os.path.exists(path):
        return json.load(open(path, encoding='utf-8'))
    return {'order': DEFAULT_ORDER, 'modes': {}}


def build(out, lay=None):
    lay = lay or layout()
    d = docx.Document(os.path.join(KURS, 'src', 'er-part.docx'))
    P = d.paragraphs
    b = Builder(d, P[1], P[4], P[6])
    body = d.element.body
    for el in list(body):
        if not el.tag.endswith('sectPr'):
            body.remove(el)
    b.heading('1.5 UML-модели представления программного средства и их описание')
    b.para('Модели представления показывают программное средство с разных точек зрения: кто и для чего им пользуется, как взаимодействуют его части, в какой последовательности выполняются действия, какие состояния принимает объект и как система размещается на оборудовании. Для описания использован унифицированный язык моделирования UML, построено по одной диаграмме каждого вида. Диаграммы последовательности, деятельности и состояний посвящены оформлению кредита – наиболее сложному процессу системы (подраздел 1.2). Диаграмма классов и ER-диаграмма приведены в подразделе 1.4.')
    order = lay['order']
    for i, key in enumerate(order):
        lead, img, title, desc = UNITS[key]
        n = FIRST + i
        mode = 'A' if i == len(order) - 1 else lay['modes'].get(key, 'A')
        b.para(lead.format(n=f'1.{n}'))
        if mode == 'B':
            b.para(desc)
        b.figure(os.path.join(KURS, f'view-{img}.png'), f'Рисунок 1.{n} – {title}')
        if mode == 'A':
            b.para(desc)
    b.para(CLOSING)
    d.save(out)
    return {key: FIRST + i for i, key in enumerate(order)}


if __name__ == '__main__':
    build(sys.argv[1])
