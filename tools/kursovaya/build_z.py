#!/usr/bin/env python3
"""Заключение пояснительной записки в оформлении образца (заголовок «ЗАКЛЮЧЕНИЕ» по центру без номера).
Использование: python3 build_z.py [выход.docx]
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm
from build_2 import Doc, KURS


def build(out):
    b = Doc(chap=0)
    h = b._p('Heading 1')
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    h.paragraph_format.first_line_indent = Cm(0)
    h.paragraph_format.left_indent = Cm(0)
    h.add_run('ЗАКЛЮЧЕНИЕ')
    b.empty()
    b.text('В ходе выполнения курсового проекта разработано программное средство дистанционного банковского обслуживания физических лиц «ТалерБанк». Цель проекта достигнута, задачи, поставленные во введении, решены.')
    b.text('Проанализирована предметная область, построены функциональная модель процесса кредитования в нотации IDEF0, информационная модель и UML-модели, сформулированы функциональные требования. Спроектировано и реализовано веб-приложение на Node.js и Express по шаблону MVC с базой данных MySQL и интерфейсом на HTML5, CSS3 и JavaScript. Все денежные операции учитываются по принципу двойной записи в транзакциях с блокировкой строк, разработаны алгоритмы переводов, начисления процентов по вкладам, построения графиков платежей и оценки кредитоспособности логистической регрессией.')
    b.text('Программное средство поддерживает шесть категорий пользователей и более пятнадцати бизнес-операций, от открытия счетов и переводов до выдачи кредитов, контроля подозрительных операций и закрытия операционного дня. Данные защищены хэшированием паролей, двухфакторной аутентификацией, защитой от подделки запросов, шифрованием паспортных данных и резервных копий. Программные тесты и тесты бизнес-логики завершились успешно, подготовлены руководства по установке и использованию.')
    b.text('Практическая значимость работы состоит в том, что клиент выполняет основные банковские операции без посещения отделения, типовая кредитная заявка рассматривается автоматически, а сотрудники банка занимаются только операциями, требующими их решения. В дальнейшем программное средство можно дополнить мобильным приложением, удалённой идентификацией клиентов, доставкой кодов по SMS и межбанковскими переводами в иностранной валюте.')
    b.save(out)


if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(KURS, 'zaklyuchenie.docx')
    build(out)
    print(out)
